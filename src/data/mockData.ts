export function formatINR(amount: number | null): string {
  if (amount === null || amount === undefined) {
    return 'Prize Unannounced';
  }
  return `₹${amount.toLocaleString('en-IN')}`;
}

export function checkStudentEligibility(
  event: HackathonEvent,
  student: StudentProfile
): EligibilityAssessment {
  if (event.eligibleYears.length === 0 || event.eligibleBranches.length === 0) {
    return {
      status: 'unknown',
      summaryLabel: 'Eligibility Unconfirmed',
      reasons: [
        'Official organizer notice has not yet specified exact academic year or department branch restrictions.',
        'Verify directly on the organizer website before paying any travel or registration costs.',
      ],
    };
  }

  const reasons: string[] = [];
  const yearMatches = event.eligibleYears.includes(student.academicYear);
  const branchMatches =
    event.eligibleBranches.includes('All Branches') ||
    event.eligibleBranches.includes(student.branch);

  if (!yearMatches) {
    reasons.push(
      `Requires ${event.eligibleYears.join(', ')} (your profile is ${student.academicYear}).`
    );
  }
  if (!branchMatches) {
    reasons.push(
      `Restricted to ${event.eligibleBranches.join(', ')} branches (your profile is ${student.branch}).`
    );
  }

  if (reasons.length > 0) {
    return {
      status: 'ineligible',
      summaryLabel: 'Not Eligible for Profile',
      reasons,
    };
  }

  return {
    status: 'eligible',
    summaryLabel: `Eligible (${student.academicYear} ${student.branch})`,
    reasons: [
      `Matches your academic year (${student.academicYear}) and department (${student.branch}).`,
    ],
  };
}

